// Exclude patterns on a SourceDirectorySet apply to every root (including the overlay), so the
// filtered vendor tree is materialized into build/ instead.
val syncVendorSources = tasks.register<Sync>("syncVendorSources") {
    from("$vendorDir/java") { exclude(vendorExcludes) }
    into(layout.buildDirectory.dir("vendor-src/java"))
}

// Android API stubs (android.*, dalvik.*; API 30), generated by :android-stubs from the AOSP API
// signature. The stub jar must not contain classes we implement: on a flat classpath (fat jar,
// embedded JVM) the stub could otherwise win and throw "Stub!". Like Suwayomi's getAndroid.sh, every
// class with a source file here (vendored AndroidCompat, overlay) is stripped, with its nested
// classes and Kotlin facades: Foo, Foo$*, FooKt, FooKt$*.
val androidStubs =
    configurations.create("androidStubs") {
        isTransitive = false
        attributes {
            attribute(Usage.USAGE_ATTRIBUTE, objects.named(Usage.JAVA_RUNTIME))
            attribute(Category.CATEGORY_ATTRIBUTE, objects.named(Category.LIBRARY))
            attribute(LibraryElements.LIBRARY_ELEMENTS_ATTRIBUTE, objects.named(LibraryElements.JAR))
        }
    }

private val implementingSources = files(syncVendorSources, "src/overlay/java", "src/main/kotlin")

fun Jar.stripImplemented(stubs: FileCollection) {
    inputs.files(implementingSources)
    dependsOn(stubs)
    val implemented =
        provider {
            implementingSources.files.filter { it.isDirectory }.flatMapTo(HashSet()) { root ->
                fileTree(root).matching { include("**/*.java", "**/*.kt") }.files.map {
                    it.relativeTo(root).invariantSeparatorsPath.substringBeforeLast('.')
                }
            }
        }
    from({ zipTree(stubs.singleFile) }) {
        exclude { element ->
            val path = element.relativePath.pathString
            val outer = path.removeSuffix(".class").substringBefore('$')
            path.endsWith(".class") && implemented.get().let { outer in it || (outer.endsWith("Kt") && outer.removeSuffix("Kt") in it) }
        }
    }
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true
}

val filteredAndroidStubs =
    tasks.register<Jar>("filteredAndroidStubs") {
        archiveFileName = "android-stubs-filtered.jar"
        destinationDirectory = layout.buildDirectory.dir("stubs")
        stripImplemented(androidStubs)
    }

tasks.test {
    // AndroidStubsOverlapTest: the filtered stubs and AndroidCompat's classes must not overlap.
    inputs.files(filteredAndroidStubs)
    systemProperty("oneechan.filteredStubs", filteredAndroidStubs.get().archiveFile.get().asFile.absolutePath)
    systemProperty("oneechan.compatClasses", sourceSets.main.get().output.classesDirs.asPath)
}

