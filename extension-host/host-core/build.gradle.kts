plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.kotlin.serialization)
}

dependencies {
    api(project(":source-api"))
    implementation(libs.apksig)
    implementation(libs.commonscompress)

    testImplementation(libs.kotlin.test.junit5)
    testImplementation(libs.coroutines.test)
    testImplementation(hostLibs.junit.jupiter)
    testImplementation(hostLibs.junit.params)
    testImplementation(hostLibs.mockwebserver)
    testRuntimeOnly(hostLibs.junit.launcher)
}

tasks.test {
    // Tests tagged "live" hit real repos and sites; run them with -Plive.
    useJUnitPlatform {
        if (!project.hasProperty("live")) excludeTags("live")
        if (!project.hasProperty("bulk")) excludeTags("bulk")
    }
    listOf("bulkRepo", "bulkLimit", "bulkApk").forEach { key -> project.findProperty(key)?.let { systemProperty("oneechan.$key", it) } }
    systemProperty("oneechan.reportDir", layout.buildDirectory.dir("reports/bulk-scan").get().asFile.absolutePath)
    maxHeapSize = if (project.hasProperty("bulk")) "6g" else "1g"
    // Extensions are R8-optimized for ART, whose verifier accepts code the JVM verifier rejects
    // (e.g. `new Object()` stored into a field typed as an uninstantiated class). The host runs
    // them like ART does: without verifying non-boot classes. Same flag in every host launcher.
    jvmArgs(JvmFlags.extensionHost)
    // Golden contract fixtures shared with the Swift client are (re)generated by the tests.
    systemProperty("oneechan.contractDir", rootProject.file("../contract").absolutePath)
    systemProperty("oneechan.updateContract", project.findProperty("updateContract") ?: "false")
    // The Swift tests write fixtures the Kotlin tests read back (e.g. backups): re-run when they change.
    inputs.dir(rootProject.file("../contract/fixtures")).withPropertyName("contractFixtures").optional()
}
